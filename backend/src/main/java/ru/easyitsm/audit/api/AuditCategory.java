package ru.easyitsm.audit.api;

/** Раздел журнала, по нему фильтрует экран «Журнал аудита» и SIEM. */
public enum AuditCategory {
    /** Вход, выход, MFA, пароли. */
    AUTH,
    /** Роли, группы, учётные записи, отказ в доступе. */
    ACCESS,
    /** Настройки процессов, форм, SLA, каталога, лицензии. */
    CONFIG,
    /** Чтение чувствительных данных, массовая выгрузка. */
    DATA,
    /** Опасные действия с повторной аутентификацией, ключи, ИИ-действия. */
    SECURITY,
    /** Действия с самим журналом: проверка целостности, выгрузка, SIEM. */
    AUDIT;

    public String code() {
        return name().toLowerCase();
    }
}
