package ru.easyitsm.identity.api;

import java.util.UUID;

/**
 * Проверка доступа к записи для текущего пользователя (ACC-01, ACC-02, ACC-04, ACC-05).
 * Роль ({@code @PreAuthorize}) отвечает на вопрос «может ли пользователь выполнять действие»,
 * а этот интерфейс — «к какой конкретно записи».
 * <p>
 * Модуль, которому запись не видна, отвечает 404, а не 403 (AT-01).
 */
public interface AccessDecisions {

    /** Область видимости для фильтра списка. */
    AccessScope currentScope();

    /** Может ли текущий пользователь читать запись с этими атрибутами. */
    boolean canRead(RecordAccess record);

    /**
     * Разделение обязанностей (ACC-05): автор не утверждает своё изменение. Если текущий пользователь —
     * автор, выбрасывает ошибку 403.
     */
    void requireNotAuthor(UUID authorId);
}
