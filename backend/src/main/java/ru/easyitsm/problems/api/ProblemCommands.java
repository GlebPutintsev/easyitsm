package ru.easyitsm.problems.api;

/**
 * Создание проблемы другими модулями: разбор крупного инцидента (MIM-05), позже — мониторинг и ИИ-помощник.
 * Выполняется в транзакции и арендаторе вызывающего; права пользователя вызывающий проверяет сам.
 */
public interface ProblemCommands {

    /**
     * Создаёт заявку типа problem, связывает инциденты ({@code caused_by}) и заводит данные проблемы.
     * Неизвестный инцидент — 404, не инцидент — 400 {@code not_incident}.
     */
    ProblemRef create(NewProblem problem);
}
