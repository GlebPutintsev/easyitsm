package ru.easyitsm.licensing.api;

/** Состояние лицензии инсталляции. */
public enum LicenseState {
    /** Файл лицензии не установлен: пробный режим с ограничением числа агентов. */
    TRIAL,
    /** Лицензия действует. */
    VALID,
    /** Срок действия ещё не начался. */
    NOT_YET_VALID,
    /** Срок действия закончился. */
    EXPIRED,
    /** Файл повреждён, подпись не сходится или ключ неизвестен. */
    INVALID
}
